"""WoTAgent CLI -- subcommands for repl, log, and api.

Usage:
    wotagent repl              Interactive chat REPL
    wotagent log               Tail the wotagent.log file
    wotagent api               Start the FastAPI server with WebSocket endpoints
"""

from __future__ import annotations

import argparse
import os
import sys
from pathlib import Path

# Ensure project src is on the path when run as `python -m wotagent.cli`
_src = Path(__file__).resolve().parent.parent
if str(_src) not in sys.path:
    sys.path.insert(0, str(_src))

from dotenv import load_dotenv

_env_path = Path(__file__).resolve().parents[3] / ".env"
load_dotenv(_env_path, encoding="utf-8")


# ---------------------------------------------------------------------------
# Interactive .env setup wizard
# ---------------------------------------------------------------------------

_ENV_TEMPLATE = """# WoTAgent -- Environment Configuration
# Auto-generated by setup wizard. Edit as needed.

# --- LLM (OpenAI-compatible) ---
LLM_MODEL={model}
OPENAI_BASE_URL={base_url}
OPENAI_API_KEY={api_key}

# --- Thinking Mode ---
ENABLE_THINKING={thinking}

# --- Perception ---
ENABLE_PERCEPTION_AUTO_EXEC={auto_exec}

# --- MCP Transport ---
MCP_TRANSPORT_MODE=stdio

# --- Embeddings (for RAG) ---
EMBED_PROVIDER=hf
EMBED_MODEL=BAAI/bge-small-zh-v1.5
"""


def _prompt(label: str, default: str = "", sensitive: bool = False) -> str:
    """Prompt the user with a label and optional default value."""
    if default:
        prompt_text = f"{label} [{default}]: "
    else:
        prompt_text = f"{label}: "

    if sensitive:
        import getpass
        value = getpass.getpass(prompt_text)
    else:
        value = input(prompt_text).strip()
    return value if value else default


def _setup_env() -> None:
    """Interactive first-time setup wizard for .env configuration."""
    env_path = _env_path
    if env_path.exists():
        return

    print()
    print("=" * 70)
    print("  Welcome to WoTAgent -- First-Time Setup")
    print("=" * 70)
    print()
    print("  No .env file found. Let's configure the essentials.")
    print()

    api_key = _prompt("  Enter your DeepSeek / OpenAI API Key", sensitive=True)
    if not api_key:
        api_key = "your-api-key-here"

    base_url = _prompt("  API Base URL", default="https://api.deepseek.com")
    model = _prompt("  Model name", default="deepseek-v4-flash")
    thinking = _prompt("  Enable thinking chain? (true/false)", default="true")
    auto_exec = _prompt("  Auto-execute triggered rules? (true/false)", default="false")

    content = _ENV_TEMPLATE.format(
        model=model, base_url=base_url, api_key=api_key,
        thinking=thinking, auto_exec=auto_exec,
    )
    env_path.write_text(content, encoding="utf-8")
    print(f"\n  Created .env at {env_path}\n")
    load_dotenv(env_path, encoding="utf-8")


def _run_repl(args: argparse.Namespace) -> None:
    """Launch the interactive chat REPL."""
    _setup_env()
    import asyncio
    enable_thinking = args.thinking
    enable_streaming = args.streaming

    from wotagent.cli.repl import run_repl
    asyncio.run(run_repl(
        log_mode="file",
        enable_thinking=enable_thinking,
        enable_streaming=enable_streaming,
    ))


def _run_log(args: argparse.Namespace) -> None:
    """Tail the WoTAgent log file to stdout."""
    _setup_env()
    import asyncio
    sys.stdout.reconfigure(encoding="utf-8", errors="replace")
    log_path = args.file
    if log_path == "wotagent.log":
        log_path = str(Path(__file__).resolve().parents[3] / "wotagent.log")

    from wotagent.cli.log import run_log_viewer
    asyncio.run(run_log_viewer(log_file=log_path, follow=not args.no_follow))


def _run_api(args: argparse.Namespace) -> None:
    """Start the FastAPI server."""
    _setup_env()
    import uvicorn
    from wotagent.logging import configure_logging
    configure_logging(mode="console")
    print(f"  WoTAgent API  -> http://{args.host}:{args.port}")
    print(f"  WebSocket     -> ws://{args.host}:{args.port}/ws")
    uvicorn.run(
        "wotagent.api.app:app",
        host=args.host,
        port=args.port,
        reload=args.reload,
        log_level="info",
    )


def main() -> None:
    parser = argparse.ArgumentParser(
        prog="wotagent",
        description="WoTAgent -- Event-driven IoT Agent with LangChain",
    )
    sub = parser.add_subparsers(dest="command", required=True)

    repl_parser = sub.add_parser("repl", help="Interactive chat REPL")
    repl_parser.add_argument("--thinking", action="store_true", default=None)
    repl_parser.add_argument("--no-thinking", action="store_false", dest="thinking", default=None)
    repl_parser.add_argument("--streaming", action="store_true", default=None)
    repl_parser.add_argument("--no-streaming", action="store_false", dest="streaming", default=None)

    log_parser = sub.add_parser("log", help="Tail wotagent.log")
    log_parser.add_argument("-f", "--file", default="wotagent.log", help="Log file path")
    log_parser.add_argument("--no-follow", action="store_true", help="Print and exit")

    api_parser = sub.add_parser("api", help="Start the FastAPI server")
    api_parser.add_argument("--host", default="127.0.0.1", help="Bind host")
    api_parser.add_argument("--port", type=int, default=8000, help="Bind port")
    api_parser.add_argument("--reload", action="store_true", help="Auto-reload on code changes")

    args = parser.parse_args()
    if args.command == "repl":
        _run_repl(args)
    elif args.command == "log":
        _run_log(args)
    elif args.command == "api":
        _run_api(args)


if __name__ == "__main__":
    main()
